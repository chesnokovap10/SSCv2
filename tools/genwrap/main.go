func main() {
	for _, l := range libs {
		old, _ := filepath.Glob(filepath.Join(l.pkgDir, l.prefix+"*"))
		for _, o := range old {
			os.Remove(o)
		}
		var srcs []string
		for _, pat := range l.files {
			m, err := filepath.Glob(filepath.Join(l.root, pat))
			if err != nil || len(m) == 0 {
				fmt.Fprintf(os.Stderr, "no match: %s\n", pat)
				os.Exit(1)
			}
			srcs = append(srcs, m...)
		}
		sort.Strings(srcs)
		n := 0
		rel, _ := filepath.Rel(l.pkgDir, ".")
		for _, s := range srcs {
			r, _ := filepath.Rel(l.root, s)
			if l.skip[filepath.ToSlash(r)] {
				continue
			}
			n++
			name := l.prefix + strings.NewReplacer("/", "_", "\\", "_", "-", "_").Replace(strings.TrimSuffix(r, filepath.Ext(r))) + l.ext
			inc := filepath.ToSlash(filepath.Join(rel, s))
			body := fmt.Sprintf("// Code generated by tools/genwrap. DO NOT EDIT.\n%s#include \"%s\"\n", l.prelude, inc)
			body += l.extra[filepath.ToSlash(r)]
			if err := os.WriteFile(filepath.Join(l.pkgDir, name), []byte(body), 0o644); err != nil {
				panic(err)
			}
		}
		fmt.Printf("%s: %d wrappers\n", l.pkgDir, len(srcs))
	}
}
