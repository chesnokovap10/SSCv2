// genwrap writes one tiny wrapper source per third-party C/C++ file into a
// Go package directory, so plain `go build` (cgo) compiles the libraries
// without CMake. Each wrapper is its own translation unit, which keeps the
// libraries' file-static symbols apart.
//
//	go run ./tools/genwrap
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type lib struct {
	pkgDir string   // Go package receiving the wrappers
	prefix string   // wrapper file name prefix
	root   string   // library root, relative to the repo
	files  []string // sources relative to root (globs allowed)
	ext    string   // wrapper extension (.c / .cpp)
	// extra code appended to the wrapper of one source (it can reach that
	// source's file-static functions)
	extra map[string]string
	// prelude goes before the #include in every wrapper
	prelude string
	// skip: sources the globs match that are not compiled on their own
	skip map[string]bool
}

